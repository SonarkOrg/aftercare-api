CREATE TABLE retention_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode VARCHAR(16) NOT NULL,
    run_trigger VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP(6) WITH TIME ZONE,
    follow_ups BIGINT DEFAULT 0 NOT NULL,
    check_ins BIGINT DEFAULT 0 NOT NULL,
    alerts BIGINT DEFAULT 0 NOT NULL,
    documents BIGINT DEFAULT 0 NOT NULL,
    messages BIGINT DEFAULT 0 NOT NULL,
    notifications BIGINT DEFAULT 0 NOT NULL,
    audit_events BIGINT DEFAULT 0 NOT NULL,
    actor_sub VARCHAR(255) NOT NULL,
    actor_name VARCHAR(255),
    CONSTRAINT retention_runs_mode_check CHECK (mode IN ('DRY_RUN', 'PURGE')),
    CONSTRAINT retention_runs_run_trigger_check CHECK (run_trigger IN ('SCHEDULED', 'MANUAL')),
    CONSTRAINT retention_runs_status_check CHECK (status IN ('SUCCEEDED', 'FAILED'))
);
CREATE INDEX idx_retention_runs_started ON retention_runs (started_at);
