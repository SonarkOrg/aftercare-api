CREATE TABLE notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,                -- no FK (rows are cleaned on patient delete and by retention)
    follow_up_id BIGINT,
    appointment_id BIGINT,
    channel VARCHAR(8) NOT NULL,
    template_key VARCHAR(32) NOT NULL,
    language VARCHAR(8) NOT NULL,
    status VARCHAR(16) NOT NULL,
    automated BOOLEAN NOT NULL,
    dedupe_key VARCHAR(120),
    attempts INTEGER DEFAULT 0 NOT NULL,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_error VARCHAR(32),
    recipient_masked VARCHAR(80),
    provider_message_id VARCHAR(64),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by_sub VARCHAR(255) NOT NULL,
    created_by_name VARCHAR(255),
    sent_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT,
    CONSTRAINT uk_outbox_dedupe UNIQUE (dedupe_key),
    CONSTRAINT notification_outbox_channel_check CHECK (channel IN ('EMAIL', 'SMS')),
    CONSTRAINT notification_outbox_template_key_check CHECK (template_key IN ('FOLLOW_UP_LINK', 'CHECKIN_REMINDER', 'APPOINTMENT_LINK', 'APPOINTMENT_REMINDER')),
    CONSTRAINT notification_outbox_language_check CHECK (language IN ('FR', 'EN')),
    CONSTRAINT notification_outbox_status_check CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED', 'CANCELLED', 'SKIPPED')),
    CONSTRAINT notification_outbox_last_error_check CHECK (last_error IN ('PROVIDER_ERROR', 'PROVIDER_REJECTED', 'INVALID_RECIPIENT', 'NO_CONSENT', 'CHANNEL_DISABLED', 'LINK_UNAVAILABLE', 'NOT_APPLICABLE', 'VOLUME_LIMIT'))
);
CREATE INDEX idx_outbox_status_next ON notification_outbox (status, next_attempt_at);
