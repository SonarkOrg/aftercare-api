ALTER TABLE staff_members ADD COLUMN access_role VARCHAR(16);
UPDATE staff_members SET access_role = CASE
    WHEN role IN ('PHYSICIAN', 'SURGEON', 'ANESTHESIOLOGIST') THEN 'PHYSICIAN'
    WHEN role IN ('NURSE', 'NURSE_PRACTITIONER') THEN 'NURSE'
    ELSE 'RECEPTION' END;
ALTER TABLE staff_members ALTER COLUMN access_role SET NOT NULL;
ALTER TABLE staff_members ADD CONSTRAINT staff_members_access_role_check
    CHECK (access_role IN ('ADMIN', 'PHYSICIAN', 'NURSE', 'RECEPTION'));
CREATE INDEX idx_staff_access_role ON staff_members (access_role, active);

